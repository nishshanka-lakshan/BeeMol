function normalizeXYZ(raw){

  const lines = String(raw).replace(/^\uFEFF/, '').split(/\r?\n/);
  while (lines.length && !lines[0].trim()) lines.shift();
  if (!lines.length) throw new Error("No coordinates found");
  const coordinateLines = /^\d+$/.test(lines[0].trim())
    ? lines.slice(2) : lines;

  const atomLines = [];

  for(const line of coordinateLines){

    const p = line.trim().split(/\s+/);

    if(p.length < 4) continue;

    const element = p[0];

    const x = Number(p[1]);

    const y = Number(p[2]);

    const z = Number(p[3]);

    if(

      /^[A-Za-z]{1,3}$/.test(element) &&

      Number.isFinite(x) &&

      Number.isFinite(y) &&

      Number.isFinite(z)

    ){

      atomLines.push(`${element}   ${x}   ${y}   ${z}`);

    }

  }

  if(atomLines.length === 0){

    throw new Error("No valid atom coordinates found");

  }

  // Rebuild the atom count automatically.

  return `${atomLines.length}\nGenerated by BeeMol\n${atomLines.join("\n")}`;

}

function getAtomLines(raw){

  const normalized = normalizeXYZ(raw);

  const lines = normalized.trim().split(/\r?\n/);

  return lines.slice(2).filter(l=>l.trim());

}

function getXYZAtoms(){

  const xyz = normalizeXYZ(document.getElementById("xyzInput").value);

  const lines = xyz.trim().split(/\r?\n/).slice(2);

  return lines.map((line, index)=>{

    const p = line.trim().split(/\s+/);

    return {

      index,

      element:p[0],

      x:Number(p[1]),

      y:Number(p[2]),

      z:Number(p[3])

    };

  });

}

function writeXYZAtoms(atoms){

  const lines = atoms.map(atom =>

    `${atom.element}   ${atom.x.toFixed(8)}   ${atom.y.toFixed(8)}   ${atom.z.toFixed(8)}`

  );

  document.getElementById("xyzInput").value =

    `${atoms.length}\nGenerated by BeeMol\n${lines.join("\n")}`;

}

function atomLabel(atom, index){

  return `${atom.element}${index + 1}`;

}

function updateBondSelectionStatus(){

  const status = document.getElementById("bondSelectionStatus");

  const atoms = getXYZAtoms();

  if(selectedBondAtoms.length === 0){

    status.textContent = "Click 2 atoms for distance, 3 for angle, or 4 for dihedral.";

    return;

  }

  if(selectedBondAtoms.length === 1){

    const i = selectedBondAtoms[0];

    status.textContent =

      `Atom 1: ${atomLabel(atoms[i], i)} selected. Now click atom 2.`;

    return;

  }

  if(selectedBondAtoms.length>=3){
    const result=BeeMolMeasurements.calculate(selectedBondAtoms.map(i=>[atoms[i].x,atoms[i].y,atoms[i].z]));
    const kind=selectedBondAtoms.length===3?'Angle':'Dihedral';
    status.textContent=`${selectedBondAtoms.map(i=>atomLabel(atoms[i],i)).join(' → ')}: ${kind} ${result?result.value.toFixed(2)+'°':'undefined (coincident or collinear atoms)'}. ${selectedBondAtoms.length===3?'Click a fourth atom for dihedral.':'Click a new atom to start again.'}`;
    return;
  }

  const i = selectedBondAtoms[0];

  const j = selectedBondAtoms[1];

  const a = atoms[i];

  const b = atoms[j];

  const dx = b.x - a.x;

  const dy = b.y - a.y;

  const dz = b.z - a.z;

  const distance = Math.hypot(dx, dy, dz);

  status.textContent =

    `${atomLabel(a, i)} ↔ ${atomLabel(b, j)} selected. Current distance: ${distance.toFixed(4)} Å. Click a third atom for angle.`;

  document.getElementById("bondLengthInput").value =

    distance.toFixed(4);

}

