function atomBlock(){

  const lines = getAtomLines(document.getElementById("xyzInput").value);

  return lines.map(line => {

    const p = line.trim().split(/\s+/);

    return `    ${p[0]}   ${p[1]}   ${p[2]}   ${p[3]}`;

  }).join("\n");

}

function commonMolCode(){

  const basis = document.getElementById("basis").value;

  const charge = document.getElementById("charge").value;

  const spin = document.getElementById("spin").value;

  const memory = document.getElementById("memory").value;

  const verbose = document.getElementById("verbose").value;

  const chk = document.getElementById("checkpoint").checked;

  const jobName = document.getElementById("jobName").value.trim() || "pyscf_job";

  return `mol = gto.M(
    atom='''\n${atomBlock()}\n    ''',
    basis='${basis}',
    charge=${charge},
    spin=${spin},
    max_memory=${memory},
    verbose=${verbose},
)${chk ? `\n\nchkfile = '${jobName}.chk'` : ""}`;

}

function scfSetup(type="RHF"){

  const convTol = document.getElementById("convTol").value;

  const maxCycle = document.getElementById("maxCycle").value;

  const densityFit = document.getElementById("densityFit").checked;

  let code = `mf = scf.${type}(mol)`;

  if(densityFit) code += `.density_fit()`;

  code += `\nmf.conv_tol = ${convTol}\nmf.max_cycle = ${maxCycle}`;

  if(document.getElementById("checkpoint").checked) code += `\nmf.chkfile = chkfile`;

  code += `\nmf.kernel()`;

  return code;

}

function generateCode(){

  try{

    const method1 = document.getElementById("method1").value;

    const method2 = document.getElementById("method2").value;

    const functional = document.getElementById("functional").value;

    const optimize = document.getElementById("optimize").checked;

    const ncas = document.getElementById("ncas").value;

    const nelecas = document.getElementById("nelecas").value;

    const nroots = document.getElementById("nroots").value;

    const adcMethod = document.getElementById("adcMethod").value;

    const adcType = document.getElementById("adcType").value;

    let imports = ["from pyscf import gto, scf"];

    let body = "";

    let post = "";

  let moldenExport = "";

 if(method1==="DFT"){

  imports = ["from pyscf import gto, dft"];

  body = `mf = dft.${Number(document.getElementById("spin").value)===0 ? "RKS" : "UKS"}(mol)\nmf.xc = '${functional}'`;

  if(document.getElementById("densityFit").checked) body += `\nmf = mf.density_fit()`;

  body += `\nmf.conv_tol = ${document.getElementById("convTol").value}\nmf.max_cycle = ${document.getElementById("maxCycle").value}`;

  if(document.getElementById("checkpoint").checked) body += `\nmf.chkfile = chkfile`;

  body += `\nmf.kernel()`;

} else {

  // RHF / ROHF / UHF reference (also used as the base for MP2/CCSD/CASSCF/CASCI/NEVPT2/ADC below)

  body = scfSetup(method1);

}

if(method2==="MP2"){

  imports.push("from pyscf import mp");

  post = `\n\npt = mp.MP2(mf)\nemp2, t2 = pt.kernel()\nprint("MP2 correlation energy =", emp2)`;

} else if(method2==="CCSD"){

  imports.push("from pyscf import cc");

  post = `\n\nmycc = cc.CCSD(mf)\nmycc.kernel()\nprint("CCSD correlation energy =", mycc.e_corr)`;

} else if(["CASSCF","CASCI","NEVPT2"].includes(method2)){

  imports.push("from pyscf import mcscf");

  if(method2==="NEVPT2") imports.push("from pyscf import mrpt");

  if(method2==="CASSCF"){

    post = `\n\nmc = mcscf.CASSCF(mf, ${ncas}, ${nelecas})\nmc.verbose = 4\n#cas_list = []\n#mo = pyscf.mcscf.sort_mo(mc, init_mo, cas_list)\nemc = mc.mc1step()[0]\nmc.analyze()`;

  } else if(method2==="CASCI"){

    post = `\n\nmc = mcscf.CASCI(mf, ${ncas}, ${nelecas})\nmc.verbose = 4\n#cas_list = []\n#mo = pyscf.mcscf.sort_mo(mc, init_mo, cas_list)\nemc = mc.kernel()[0]\nmc.analyze()`;

  } else {

    post = `\n\nmc = mcscf.CASSCF(mf, ${ncas}, ${nelecas})\nmc.verbose = 4\n#cas_list = []\n#mo = pyscf.mcscf.sort_mo(mc, init_mo, cas_list)\nemc = mc.mc1step()[0]\nmc.analyze()\n\nnev = mrpt.NEVPT(mc)\nnev.kernel()`;

  }

} else if(method2==="ADC"){

  imports.push("from pyscf import adc");

  let call = adcType==="IP" ? "ip_adc" : adcType==="EA" ? "ea_adc" : "kernel";

  post = `\n\nmyadc = adc.ADC(mf)\nmyadc.method = '${adcMethod}'\nmyadc.kernel_gs()\n# ${adcType}-ADC calculation\nresults = myadc.${call}(nroots=${nroots})`;

}

    // Export the coefficients of the chosen calculation for the Orbitals viewer.

  // CASSCF/CASCI MO energies are not generally the SCF eigenvalues, so do

  // not attach mf.mo_energy to mc.mo_coeff.

  imports.push("from pyscf.tools import molden");

  body += `\nmf.analyze()\n\n\n# Open this file in BeeMol's Orbitals tab\nmolden.from_mo(mf.mol, 'scf.molden', mf.mo_coeff)`;

  if(["CASSCF", "CASCI", "NEVPT2"].includes(method2)){

    moldenExport += `\n\n\n# CASSCF/CASCI optimized orbitals; no SCF energy assigned to them\nmolden.from_mo(mf.mol, 'casscf.molden', mc.mo_coeff)`;

  }

  if(optimize){

      imports.push("from pyscf.geomopt.geometric_solver import optimize");

      post += `\n\n# Geometry optimization\nmol_eq = optimize(mf)`;

    }

    imports.push("import pyscf\npyscf.lib.num_threads(" + document.getElementById("threads").value + ")");

    const code = `${imports.join("\n")}\n\n${commonMolCode()}\n\n${body}${post}${moldenExport}\n`;

    document.getElementById("codeOutput").textContent =

      code.trim() + "\n";

    const s = document.getElementById("codeStatus");

    s.textContent = "Ready";

    s.className = "status ok";

  }catch(err){

    document.getElementById("codeOutput").textContent = "# Error while generating input:\n# " + err.message;

    const s = document.getElementById("codeStatus");

    s.textContent = "Check geometry";

    s.className = "status err";

  }

}

