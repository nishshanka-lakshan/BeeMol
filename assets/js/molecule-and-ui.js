// Atom count determines distance, angle, or signed dihedral.
function showSelectedMeasurement(){
  const atoms=viewer.selectedAtoms({});
  const indices=selectedBondAtoms.filter(i=>atoms[i]);
  const readout=document.getElementById("moleculeMeasurement");
  readout.hidden=indices.length<2;
  readout.textContent="";
  if(indices.length<2){
    viewer.setMeasurements(indices.length?[{indices}]:[]);
    return;
  }
  const result=BeeMolMeasurements.calculate(indices.map(i=>[atoms[i].x,atoms[i].y,atoms[i].z]));
  const kind=indices.length===2?'Distance':indices.length===3?'Angle':'Dihedral';
  readout.textContent=`${kind}: ${result?result.value.toFixed(indices.length===2?4:2)+' '+result.unit:'Undefined'}`;
  viewer.setMeasurements([{indices}]);
}

function enableBondAtomSelection(){

  if(!viewer || typeof viewer.setClickable !== "function") return;

  viewer.onGeometryClear=()=>{selectedBondAtoms=[];updateBondSelectionStatus();showSelectedMeasurement();};
  viewer.setClickable({}, true, function(atom){

    let index;

    if(Number.isInteger(atom.index)){

      index = atom.index;

    }else if(Number.isFinite(Number(atom.serial))){

      index = Number(atom.serial) - 1;

    }else{

      return;

    }

    if(selectedBondAtoms.length >= 4 && !selectedBondAtoms.includes(index)){

      selectedBondAtoms = [];

    }

    if(selectedBondAtoms.includes(index)){

      // Clicking the same selected atom removes it.

      selectedBondAtoms =

        selectedBondAtoms.filter(i => i !== index);

    }else{

      selectedBondAtoms.push(index);

    }

    updateBondSelectionStatus();

    applySelectionStyle();

  });

}

function clearBondSelection(){

  selectedBondAtoms = [];

  updateBondSelectionStatus();

  applySelectionStyle();

}

function applySelectedBondLength(){

  if(selectedBondAtoms.length !== 2){

    alert("Select two atoms in the 3D viewer first.");

    return;

  }

  const targetLength =

    Number(document.getElementById("bondLengthInput").value);

  if(!Number.isFinite(targetLength) || targetLength <= 0){

    alert("Enter a valid positive bond length.");

    return;

  }

  const atoms = getXYZAtoms();

  const fixedIndex = selectedBondAtoms[0];

  const movingIndex = selectedBondAtoms[1];

  const atom1 = atoms[fixedIndex];

  const atom2 = atoms[movingIndex];

  const dx = atom2.x - atom1.x;

  const dy = atom2.y - atom1.y;

  const dz = atom2.z - atom1.z;

  const currentLength = Math.hypot(dx, dy, dz);

  if(currentLength < 1.0e-10){

    alert("The selected atoms are at the same coordinates, so the bond direction is undefined.");

    return;

  }

  // Unit vector from atom 1 to atom 2.

  const ux = dx / currentLength;

  const uy = dy / currentLength;

  const uz = dz / currentLength;

  // Keep atom 1 fixed and move atom 2 along the same direction.

  atom2.x = atom1.x + targetLength * ux;

  atom2.y = atom1.y + targetLength * uy;

  atom2.z = atom1.z + targetLength * uz;

  writeXYZAtoms(atoms);

  // Refresh the 3D structure and generated PySCF input.

  loadMolecule();

  // Keep the same two atoms selected after rebuilding.

  selectedBondAtoms = [fixedIndex, movingIndex];

  updateBondSelectionStatus();

  applySelectionStyle();

}

