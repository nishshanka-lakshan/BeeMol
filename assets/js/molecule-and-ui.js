function normalizeXYZ(raw){

  const lines = String(raw).replace(/^\uFEFF/, '').split(/\r?\n/);
  while (lines.length && !lines[0].trim()) lines.shift();
  if (!lines.length) throw new Error("No coordinates found");
  const coordinateLines = /^\d+$/.test(lines[0].trim())
    ? lines.slice(2) : lines;

  const atomLines = [];

  for(const line of coordinateLines){

    const p = line.trim().split(/\s+/);

    if(p.length < 4) continue;

    const element = p[0];

    const x = Number(p[1]);

    const y = Number(p[2]);

    const z = Number(p[3]);

    if(

      /^[A-Za-z]{1,3}$/.test(element) &&

      Number.isFinite(x) &&

      Number.isFinite(y) &&

      Number.isFinite(z)

    ){

      atomLines.push(`${element}   ${x}   ${y}   ${z}`);

    }

  }

  if(atomLines.length === 0){

    throw new Error("No valid atom coordinates found");

  }

  // Rebuild the atom count automatically.

  return `${atomLines.length}\nGenerated by BeeMol\n${atomLines.join("\n")}`;

}

function getAtomLines(raw){

  const normalized = normalizeXYZ(raw);

  const lines = normalized.trim().split(/\r?\n/);

  return lines.slice(2).filter(l=>l.trim());

}

function getXYZAtoms(){

  const xyz = normalizeXYZ(document.getElementById("xyzInput").value);

  const lines = xyz.trim().split(/\r?\n/).slice(2);

  return lines.map((line, index)=>{

    const p = line.trim().split(/\s+/);

    return {

      index,

      element:p[0],

      x:Number(p[1]),

      y:Number(p[2]),

      z:Number(p[3])

    };

  });

}

function writeXYZAtoms(atoms){

  const lines = atoms.map(atom =>

    `${atom.element}   ${atom.x.toFixed(8)}   ${atom.y.toFixed(8)}   ${atom.z.toFixed(8)}`

  );

  document.getElementById("xyzInput").value =

    `${atoms.length}\nGenerated by BeeMol\n${lines.join("\n")}`;

}

function atomLabel(atom, index){

  return `${atom.element}${index + 1}`;

}

function updateBondSelectionStatus(){

  const status = document.getElementById("bondSelectionStatus");

  const atoms = getXYZAtoms();

  if(selectedBondAtoms.length === 0){

    status.textContent = "Bond edit: click two atoms in the 3D viewer";

    return;

  }

  if(selectedBondAtoms.length === 1){

    const i = selectedBondAtoms[0];

    status.textContent =

      `Atom 1: ${atomLabel(atoms[i], i)} selected. Now click atom 2.`;

    return;

  }

  const i = selectedBondAtoms[0];

  const j = selectedBondAtoms[1];

  const a = atoms[i];

  const b = atoms[j];

  const dx = b.x - a.x;

  const dy = b.y - a.y;

  const dz = b.z - a.z;

  const distance = Math.hypot(dx, dy, dz);

  status.textContent =

    `${atomLabel(a, i)} ↔ ${atomLabel(b, j)} selected. Current distance: ${distance.toFixed(4)} Å`;

  document.getElementById("bondLengthInput").value =

    distance.toFixed(4);

}

function applySelectionStyle(){

  if(!viewer) return;

  viewer.setStyle(

    {},

    ballStick

      ? {stick:{radius:0.18}, sphere:{scale:0.28}}

      : {line:{}}

  );

    colorMoleculeAtoms();

selectedBondAtoms.forEach((atomIndex, selectionNumber)=>{

    viewer.setStyle(

      {index:atomIndex},

      {

        stick:{radius:0.24},

        sphere:{

          scale:0.42,

          color: selectionNumber === 0 ? "yellow" : "cyan"

        }

      }

    );

  });

  viewer.render();

}

function enableBondAtomSelection(){

  if(!viewer || typeof viewer.setClickable !== "function") return;

  viewer.setClickable({}, true, function(atom){

    let index;

    if(Number.isInteger(atom.index)){

      index = atom.index;

    }else if(Number.isFinite(Number(atom.serial))){

      index = Number(atom.serial) - 1;

    }else{

      return;

    }

    if(selectedBondAtoms.length >= 2){

      selectedBondAtoms = [];

    }

    if(selectedBondAtoms.includes(index)){

      // Clicking the same selected atom removes it.

      selectedBondAtoms =

        selectedBondAtoms.filter(i => i !== index);

    }else{

      selectedBondAtoms.push(index);

    }

    updateBondSelectionStatus();

    applySelectionStyle();

  });

}

function clearBondSelection(){

  selectedBondAtoms = [];

  updateBondSelectionStatus();

  applySelectionStyle();

}

function applySelectedBondLength(){

  if(selectedBondAtoms.length !== 2){

    alert("Select two atoms in the 3D viewer first.");

    return;

  }

  const targetLength =

    Number(document.getElementById("bondLengthInput").value);

  if(!Number.isFinite(targetLength) || targetLength <= 0){

    alert("Enter a valid positive bond length.");

    return;

  }

  const atoms = getXYZAtoms();

  const fixedIndex = selectedBondAtoms[0];

  const movingIndex = selectedBondAtoms[1];

  const atom1 = atoms[fixedIndex];

  const atom2 = atoms[movingIndex];

  const dx = atom2.x - atom1.x;

  const dy = atom2.y - atom1.y;

  const dz = atom2.z - atom1.z;

  const currentLength = Math.hypot(dx, dy, dz);

  if(currentLength < 1.0e-10){

    alert("The selected atoms are at the same coordinates, so the bond direction is undefined.");

    return;

  }

  // Unit vector from atom 1 to atom 2.

  const ux = dx / currentLength;

  const uy = dy / currentLength;

  const uz = dz / currentLength;

  // Keep atom 1 fixed and move atom 2 along the same direction.

  atom2.x = atom1.x + targetLength * ux;

  atom2.y = atom1.y + targetLength * uy;

  atom2.z = atom1.z + targetLength * uz;

  writeXYZAtoms(atoms);

  // Refresh the 3D structure and generated PySCF input.

  loadMolecule();

  // Keep the same two atoms selected after rebuilding.

  selectedBondAtoms = [fixedIndex, movingIndex];

  updateBondSelectionStatus();

  applySelectionStyle();

}

function loadMolecule(){

  try{

    const raw = document.getElementById("xyzInput").value;

    const xyz = normalizeXYZ(raw);

    viewer.clear();

    viewer.addModel(xyz, "xyz");

    viewer.setStyle(

      {},

      ballStick

        ? {stick:{radius:0.18}, sphere:{scale:0.28}}

        : {line:{}}

    );

        colorMoleculeAtoms();

enableBondAtomSelection();

// Update when the Three.js renderer is ready

    viewer.ready.then(() => {

      viewer.zoomTo();

      viewer.resize();

      viewer.render();

    }).catch(error => {

      console.error("Molecule viewer failed:", error);

    });

    // Reapply selection highlighting after the model is rebuilt.

    if(selectedBondAtoms.length){

      applySelectionStyle();

    }

    const n = getAtomLines(raw).length;

    document.getElementById("atomCount").textContent = `${n} atom${n===1?"":"s"}`;

    const s = document.getElementById("geomStatus");

    s.textContent = "Geometry loaded";

    s.className = "status ok";

    generateCode();

  }catch(err){

    const s = document.getElementById("geomStatus");

    s.textContent = err.message;

    s.className = "status err";

  }

}

function atomBlock(){

  const lines = getAtomLines(document.getElementById("xyzInput").value);

  return lines.map(line => {

    const p = line.trim().split(/\s+/);

    return `    ${p[0]}   ${p[1]}   ${p[2]}   ${p[3]}`;

  }).join("\n");

}

function commonMolCode(){

  const basis = document.getElementById("basis").value;

  const charge = document.getElementById("charge").value;

  const spin = document.getElementById("spin").value;

  const memory = document.getElementById("memory").value;

  const verbose = document.getElementById("verbose").value;

  const chk = document.getElementById("checkpoint").checked;

  const jobName = document.getElementById("jobName").value.trim() || "pyscf_job";

  return `mol = gto.M(

    atom='''\n${atomBlock()}\n    ''',

    basis='${basis}',

    charge=${charge},

    spin=${spin},

    max_memory=${memory},

    verbose=${verbose},

)${chk ? `\n\nchkfile = '${jobName}.chk'` : ""}`;

}

function scfSetup(type="RHF"){

  const convTol = document.getElementById("convTol").value;

  const maxCycle = document.getElementById("maxCycle").value;

  const densityFit = document.getElementById("densityFit").checked;

  let code = `mf = scf.${type}(mol)`;

  if(densityFit) code += `.density_fit()`;

  code += `\nmf.conv_tol = ${convTol}\nmf.max_cycle = ${maxCycle}`;

  if(document.getElementById("checkpoint").checked) code += `\nmf.chkfile = chkfile`;

  code += `\nmf.kernel()`;

  return code;

}

function generateCode(){

  try{

    const method1 = document.getElementById("method1").value;

    const method2 = document.getElementById("method2").value;

    const functional = document.getElementById("functional").value;

    const optimize = document.getElementById("optimize").checked;

    const ncas = document.getElementById("ncas").value;

    const nelecas = document.getElementById("nelecas").value;

    const nroots = document.getElementById("nroots").value;

    const adcMethod = document.getElementById("adcMethod").value;

    const adcType = document.getElementById("adcType").value;

    let imports = ["from pyscf import gto, scf"];

    let body = "";

    let post = "";

  let moldenExport = "";

 if(method1==="DFT"){

  imports = ["from pyscf import gto, dft"];

  body = `mf = dft.${Number(document.getElementById("spin").value)===0 ? "RKS" : "UKS"}(mol)\nmf.xc = '${functional}'`;

  if(document.getElementById("densityFit").checked) body += `\nmf = mf.density_fit()`;

  body += `\nmf.conv_tol = ${document.getElementById("convTol").value}\nmf.max_cycle = ${document.getElementById("maxCycle").value}`;

  if(document.getElementById("checkpoint").checked) body += `\nmf.chkfile = chkfile`;

  body += `\nmf.kernel()`;

} else {

  // RHF / ROHF / UHF reference (also used as the base for MP2/CCSD/CASSCF/CASCI/NEVPT2/ADC below)

  body = scfSetup(method1);

}

if(method2==="MP2"){

  imports.push("from pyscf import mp");

  post = `\n\npt = mp.MP2(mf)\nemp2, t2 = pt.kernel()\nprint("MP2 correlation energy =", emp2)`;

} else if(method2==="CCSD"){

  imports.push("from pyscf import cc");

  post = `\n\nmycc = cc.CCSD(mf)\nmycc.kernel()\nprint("CCSD correlation energy =", mycc.e_corr)`;

} else if(["CASSCF","CASCI","NEVPT2"].includes(method2)){

  imports.push("from pyscf import mcscf");

  if(method2==="NEVPT2") imports.push("from pyscf import mrpt");

  if(method2==="CASSCF"){

    post = `\n\nmc = mcscf.CASSCF(mf, ${ncas}, ${nelecas})\nmc.verbose = mol.verbose\nmc.kernel()`;

  } else if(method2==="CASCI"){

    post = `\n\nmc = mcscf.CASCI(mf, ${ncas}, ${nelecas})\nmc.verbose = mol.verbose\nmc.kernel()`;

  } else {

    post = `\n\nmc = mcscf.CASSCF(mf, ${ncas}, ${nelecas})\nmc.verbose = mol.verbose\nmc.kernel()\n\nnev = mrpt.NEVPT(mc)\nnev.kernel()`;

  }

} else if(method2==="ADC"){

  imports.push("from pyscf import adc");

  let call = adcType==="IP" ? "ip_adc" : adcType==="EA" ? "ea_adc" : "kernel";

  post = `\n\nmyadc = adc.ADC(mf)\nmyadc.method = '${adcMethod}'\nmyadc.kernel_gs()\n# ${adcType}-ADC calculation\nresults = myadc.${call}(nroots=${nroots})`;

}

    // Export the coefficients of the chosen calculation for the Orbitals viewer.

  // CASSCF/CASCI MO energies are not generally the SCF eigenvalues, so do

  // not attach mf.mo_energy to mc.mo_coeff.

  imports.push("from pyscf.tools import molden");

  const jobName = document.getElementById("jobName").value.trim() || "pyscf_job";

  moldenExport = `\n\n# Open this file in BeeMol's Orbitals tab\nmolden.from_scf(mf, '${jobName}_scf.molden')`;

  if(["CASSCF", "CASCI", "NEVPT2"].includes(method2)){

    moldenExport += `\n# CASSCF/CASCI optimized orbitals; no SCF energy assigned to them\nmolden.from_mo(mol, '${jobName}_cas.molden', mc.mo_coeff)`;

  }

  if(optimize){

      imports.push("from pyscf.geomopt.geometric_solver import optimize");

      post += `\n\n# Geometry optimization\nmol_eq = optimize(mf)`;

    }

    imports.push("import pyscf\npyscf.lib.num_threads(" + document.getElementById("threads").value + ")");

    const code = `${imports.join("\n")}\n\n${commonMolCode()}\n\n${body}${post}${moldenExport}\n`;

    document.getElementById("codeOutput").textContent =

      code.replace(/\n[ \t]*\n(?:[ \t]*\n)+/g, "\n\n").trim() + "\n";

    const s = document.getElementById("codeStatus");

    s.textContent = "Ready";

    s.className = "status ok";

  }catch(err){

    document.getElementById("codeOutput").textContent = "# Error while generating input:\n# " + err.message;

    const s = document.getElementById("codeStatus");

    s.textContent = "Check geometry";

    s.className = "status err";

  }

}

