function unitVector(v){

  const norm=Math.hypot(...v);

  return norm>1e-12?v.map(x=>x/norm):[1,0,0];

}

function quaternionMultiply(a,b){

  const [x,y,z,w]=a,[u,v,t,r]=b;

  return [w*u+x*r+y*t-z*v,w*v-x*t+y*r+z*u,w*t+x*v-y*u+z*r,w*r-x*u-y*v-z*t];

}

function rotateVectorByQuaternion(v,q){

  const p=quaternionMultiply(quaternionMultiply(q,[...v,0]),[-q[0],-q[1],-q[2],q[3]]);

  return p.slice(0,3);

}

function quaternionBetween(from,to){

  const a=unitVector(from),b=unitVector(to);

  const d=Math.max(-1,Math.min(1,a.reduce((sum,x,i)=>sum+x*b[i],0)));

  if(d < -0.999999){

    const perpendicular=unitVector(Math.abs(a[0])<0.9?[0,-a[2],a[1]]:[-a[1],a[0],0]);

    return [...perpendicular,0];

  }

  const cross=[a[1]*b[2]-a[2]*b[1],a[2]*b[0]-a[0]*b[2],a[0]*b[1]-a[1]*b[0]];

  const q=[...cross,1+d],length=Math.hypot(...q);

  return q.map(x=>x/length);

}

function setOrientation(q){

  const view=viewer.getView();

  const norm=Math.hypot(...q);

  viewer.setView([...view.slice(0,4),...q.map(x=>x/norm)]);

  if(animationRunning)animationFixedView=viewer.getView();

  viewer.render();

}

function alignMolecule(axis){

  const atoms=viewer.selectedAtoms({});

  if(atoms.length<2)return;

  let first=atoms[0],last=atoms[1],distance=-1;

  for(let i=0;i<atoms.length;i++)for(let j=i+1;j<atoms.length;j++){

    const d=(atoms[i].x-atoms[j].x)**2+(atoms[i].y-atoms[j].y)**2+(atoms[i].z-atoms[j].z)**2;

    if(d>distance){distance=d;first=atoms[i];last=atoms[j]}

  }

  const direction=unitVector([last.x-first.x,last.y-first.y,last.z-first.z]);

  const view=viewer.getView();

  const current=rotateVectorByQuaternion(direction,view.slice(4));

  const target=axis==="x"?[1,0,0]:[0,1,0];

  if(current[0]*target[0]+current[1]*target[1]<0)target[0]*=-1,target[1]*=-1;

  setOrientation(quaternionMultiply(quaternionBetween(current,target),view.slice(4)));

}

